export function t(lang: Lang | undefined, key: string, vars?: Record<string, string | number>): string {
  const pack = lang === 'en' ? en : de
  let text = pack[key] ?? de[key] ?? key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value))
  }
  return text
}

export function typeLabel(lang: Lang, id: TypeId | string, german: string): string {
  return lang === 'en' ? (typesEn[id] ?? german) : german
}

export function rarityLabel(lang: Lang, index: number, german: string): string {
  return lang === 'en' ? (rarityEn[index] ?? german) : german
}

export function weatherLabel(lang: Lang, id: WeatherId): string {
  if (lang === 'en') return weatherEn[id]
  const names: Record<WeatherId, string> = { klar: 'Klar', regen: 'Regen', gewitter: 'Gewitter', schnee: 'Schnee', nebel: 'Nebel', wind: 'Wind' }
  return names[id]
}

const weatherDeToEn: Record<string, string> = {
  Klar: 'Clear', Regen: 'Rain', Gewitter: 'Storm', Schnee: 'Snow', Nebel: 'Fog', Wind: 'Wind'
}

export function whenLabel(lang: Lang, when: string): string {
  if (when === 'Tag und Nacht') return t(lang, 'when.both')
  if (when === 'nur nachts') return t(lang, 'when.night')
  if (when === 'nur tags') return t(lang, 'when.day')
  if (when === 'Wächterteam') return t(lang, 'when.guard')
  if (when === 'direkt hintereinander') return t(lang, 'when.council')
  if (when.startsWith('bei ')) {
    const name = when.slice(4)
    return t(lang, 'when.weather', { name: lang === 'en' ? (weatherDeToEn[name] ?? name) : name })
  }
  return when
}

